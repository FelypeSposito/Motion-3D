// símbolos (caixa ~1×1); w = largura
const star = (n = 5, ro = .5, ri = .21) => {
  const p = [];
  for (let i = 0; i < n * 2; i++) {
    const a = Math.PI / 2 + i * Math.PI / n, r = i % 2 ? ri : ro;
    p.push([.5 + Math.cos(a) * r, .5 + Math.sin(a) * r]);
  }
  return S(p, true);
};
const wave = (per = 2, amp = .22, n = 36) => S(Array.from({ length: n + 1 }, (_, i) => [i / n, .5 + Math.sin(i / n * per * Math.PI * 2) * amp]));

