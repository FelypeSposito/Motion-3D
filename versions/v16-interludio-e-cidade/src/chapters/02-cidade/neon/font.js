// arco de elipse em graus (a0 → a1, qualquer sentido)
function arc(cx, cy, rx, ry, a0, a1, n = 16) {
  const out = [];
  for (let i = 0; i <= n; i++) {
    const a = (a0 + (a1 - a0) * i / n) * Math.PI / 180;
    out.push([cx + Math.cos(a) * rx, cy + Math.sin(a) * ry]);
  }
  return out;
}
const S = (p, c = false) => ({ p, c });
const ring = (cx, cy, rx, ry, n = 28) => S(arc(cx, cy, rx, ry, 0, 360, n).slice(0, -1), true);

